// QuestionFactors — факторы, о которых спрашивает пользователь.
func QuestionFactors(question string) []FactorSignal {
	var out []FactorSignal
	for _, f := range factors {
		if containsAny(question, f.Keywords) || containsAny(question, queryKeywords[f.Key]) {
			out = append(out, FactorSignal{Factor: f.Key, Name: f.Name, Direction: directionFor(f.Key, question), Evidence: shorten(question, 220)})
		}
	}
	return out
}

var factorIndex = func() map[string]*Factor {
	m := map[string]*Factor{}
	for i := range factors {
		m[factors[i].Key] = &factors[i]
	}
	return m
}()

func factorName(key string) string {
	if f, ok := factorIndex[key]; ok {
		return f.Name
	}
	return key
}

func directionPhrase(fs FactorSignal) string {
	f, ok := factorIndex[fs.Factor]
	if !ok {
		return fs.Name
	}
	switch fs.Direction {
	case "up":
		return f.UpPhrase
	case "down":
		return f.DownPhrase
	case "flat":
		return f.FlatPhrase
	}
	return "меняется " + strings.ToLower(f.Name)
}

