var sectorIndex = func() map[string]*Sector {
	m := map[string]*Sector{}
	for i := range sectors {
		m[sectors[i].Key] = &sectors[i]
	}
	return m
}()

var okvedIndex = func() map[string]string {
	m := map[string]string{}
	for _, s := range sectors {
		for _, code := range s.OKVED {
			m[code] = s.Key
		}
	}
	return m
}()

func sectorName(key string) string {
	if s, ok := sectorIndex[key]; ok {
		return s.Name
	}
	return key
}

// sectorByOKVED — отрасль по коду ОКВЭД вида «46.71.1» (берутся первые 2 цифры).
func sectorByOKVED(code string) string {
	code = strings.TrimSpace(code)
	digits := make([]rune, 0, 2)
	for _, r := range code {
		if r >= '0' && r <= '9' {
			digits = append(digits, r)
			if len(digits) == 2 {
				break
			}
		} else if r == '.' {
			break
		}
	}
	if len(digits) == 1 {
		digits = append([]rune{'0'}, digits...)
	}
	if k, ok := okvedIndex[string(digits)]; ok {
		return k
	}
	return "other"
}

