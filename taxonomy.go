// specializationFor — уточнение по самому длинному совпадающему префиксу ОКВЭД.
func specializationFor(okved string) *Specialization {
	var best *Specialization
	for i := range specializations {
		s := &specializations[i]
		if strings.HasPrefix(strings.TrimSpace(okved), s.Prefix) && (best == nil || len(s.Prefix) > len(best.Prefix)) {
			best = s
		}
	}
	return best
}
