// detectDirection определяет направление изменения фактора по предложению.
func detectDirection(sentence string) string {
	low := strings.ToLower(sentence)
	if containsAny(low, flatWords) {
		return "flat"
	}
	up, down := countAny(low, upWords), countAny(low, downWords)
	switch {
	case up > down:
		return "up"
	case down > up:
		return "down"
	}
	return "unknown"
}

